# The reviewer gets the whole instruction set, not just loop 1's: a contradiction between two
# rules in the same file is the easy case, and the one that actually bit us sits between the
# rules file and a tool schema two notebooks away.
def cells_defining(notebook, *names):
    """Pull source cells out of a notebook without executing it.

    Loop 2 is not imported: running it would fire its own approval gate, and the reviewer only
    needs to read the instructions, not run them.
    """
    nb = json.loads(Path(notebook).read_text())
    out = []
    for cell in nb["cells"]:
        src = "".join(cell["source"])
        if cell["cell_type"] == "code" and any(f"{n} = " in src for n in names):
            out.append(src)
    return "\n\n".join(out)


