def dump(path, blocks):
    out = []
    for title, body, lang in blocks:
        if title:
            out += [f"## {title}", ""]
        if body is not None:
            out += [f"```{lang}", body.rstrip(), "```", ""]
    Path(path).write_text("\n".join(out))
    print("wrote", path)


